-- 058: публикуемый получатель эскроу — ротация без пересборки агента.
--
-- Проблема, которую это закрывает. Получатель эскроу вшивался в агента ldflags'ами при
-- сборке, поэтому его смена была РЕЛИЗОМ: под macOS — нативная пересборка и раскатка
-- пакета на парк. Для стенда терпимо, для клиента нет: компрометация или плановая
-- ротация ключа кастодии не должна упираться в цикл выпуска.
--
-- Схема (предложена Тинки, принята владельцем 30.07). Получателя подписывает РЕЛИЗНЫЙ
-- ключ деплойера — тот самый, которым уже подписаны бинари агента и манифест
-- самообновления. Агент пинит релизный ключ (он приходит ему при энроллменте), а НЕ
-- получателя, и держит монотонный epoch-floor. Тогда смена получателя — публикация, а
-- не пересборка.
--
-- Почему не TOFU (доверие первому увиденному). На чистой установке первым может
-- оказаться ключ атакующего, и TOFU это не ловит — он лишь фиксирует то, что успели
-- подсунуть. Подпись релизным ключом закрывает и этот случай: скомпрометированный
-- сервер не может выпустить получателя, которому агент поверит, потому что приватника
-- релиза на сервере нет.
--
-- epoch монотонен и служит anti-rollback: агент не принимает epoch меньше уже
-- виденного, иначе откат на старого (скомпрометированного) получателя выглядел бы для
-- него нормальной публикацией. Тот же приём, что update_floor у самообновления.

CREATE TABLE IF NOT EXISTS escrow_recipients (
    epoch      BIGINT      PRIMARY KEY,
    recipient  TEXT        NOT NULL,
    fpr        TEXT        NOT NULL,
    signature  TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE escrow_recipients IS
  'Подписанные релизным ключом получатели эскроу. Глобальная таблица: кастодия одна на '
  'инсталляцию, как и релизный ключ. Строки только добавляются — история ротаций.';

