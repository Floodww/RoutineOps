-- 075: потолок профиля сеанса экрана у тенанта.
--
-- 🔴 Формат файла: ПЛОСКИЙ SQL, без goose-аннотаций. Всё, что стоит после «-- DOWN:»,
-- закомментировано и живой SQL'ой не является.
--
-- Что меняется. До сих пор профиль сеанса был КОНСТАНТОЙ `"low"` в коде создания сеанса:
-- 1 к/с, 1280 по длинной стороне. §10 контракта требовал именно этого, и требовал по
-- расчёту — худший случай (keyframe каждый кадр) давал 4.62 Мбит/с на полном Retina, а
-- ретранслирует сервер, то есть ёмкость считается как «сеансов × худший случай».
--
-- Замер на живом рабочем столе 07.08.2026 показал, что худший случай в поле не наступает
-- даже близко: два сеанса с управлением дали 23.8 и 24.7 кбит/с — 1.6–1.7 % бюджета low.
-- Keyframe стоит 133 КБ, покой ~390 Б/кадр, самая шумная работа с перетаскиванием окон —
-- ~21 КБ/кадр, то есть в шесть раз дешевле keyframe. Считать бюджет по keyframe-модели
-- значит закладываться на случай, которого не бывает.
--
-- Поэтому профиль перестаёт быть константой и становится ПОТОЛКОМ ТЕНАНТА:
--
--   * дефолт `medium` — 2 к/с вместо 1. Для пассивного просмотра это чистый выигрыш, и
--     он измерен, а не предположен;
--   * тенант на узком канале обязан мочь опуститься до `low`. Именно поэтому это
--     потолок, а не значение: сервер выдаёт профиль в приглашении, но не выше того, что
--     разрешил тенант.
--
-- Почему CHECK, а не свободный текст: неизвестное имя профиля агент трактует как low и
-- поднимает признак profile_fallback (миграция 072). Это правильное поведение агента, но
-- на стороне сервера оно означало бы «настройка выставлена, а не действует» — молча.

SET lock_timeout = '5s';

ALTER TABLE tenants
  ADD COLUMN IF NOT EXISTS screen_profile_cap TEXT NOT NULL DEFAULT 'medium';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'tenants_screen_profile_cap_check'
  ) THEN
    ALTER TABLE tenants
      ADD CONSTRAINT tenants_screen_profile_cap_check
      CHECK (screen_profile_cap IN ('low', 'medium'));
  END IF;
END $$;

COMMENT ON COLUMN tenants.screen_profile_cap IS
  'Потолок профиля сеанса экрана: low (1 к/с, 1280) или medium (2 к/с, 1920). Сервер выдаёт профиль в приглашении не выше этого значения.';

