-- 055: удаление тенанта с переездом содержимого в Default.
--
-- Решение флуда 30.07: Default удалить нельзя (переименовать можно), а при удалении
-- любого другого тенанта его устройства и люди автоматически переходят в Default —
-- ничего не пропадает и ничего не надо переносить руками заранее.
--
-- 🔴 Почему строка тенанта НЕ удаляется физически, а помечается tombstone'ом.
-- На tenants ссылаются 24 таблицы с ON DELETE NO ACTION, и среди них audit_log с
-- audit_anchors. Журнал аудита тенантский НЕ случайно: цепочка хешей у каждого
-- тенанта своя, seq сквозной внутри тенанта, а якоря фиксируют её голову. Перелить
-- записи в Default — значит склеить две независимые цепочки: seq столкнутся,
-- prev_hash перестанет сходиться, и проверка целостности покраснеет у ОБОИХ
-- тенантов. Удалить записи вместе с тенантом — значит стереть доказательную часть
-- ровно за тот период, про который потом и будут спрашивать. Поэтому журнал
-- остаётся на месте, а вместе с ним обязана остаться и строка тенанта: иначе FK.
--
-- Снаружи это неотличимо от удаления: тенант исчезает из списка, из селектора и из
-- всех выборок. Внутри — сохранённая история.

ALTER TABLE tenants ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;

-- Имя уникально только среди живых: удалённый тенант не должен мешать завести
-- новый с тем же именем, но и переиспользовать его имя молча нельзя.
CREATE UNIQUE INDEX IF NOT EXISTS tenants_name_alive_uniq
  ON tenants (lower(name)) WHERE deleted_at IS NULL;

COMMENT ON COLUMN tenants.deleted_at IS
  'Тумбстоун: тенант удалён из интерфейса, содержимое переехало в Default, но строка '
  'сохранена ради tamper-evident журнала аудита (цепочка хешей пер-тенантная).';

