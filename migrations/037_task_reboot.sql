-- 037: удалённая перезагрузка устройства. task_type получает значение 'reboot'
-- (домен колонки открытый, как и у 'lock'/'decommission' из 013 — CHECK'а нет).
--
-- Отдельные колонки, а не переиспользование lock_reason: причина лока едет агенту в
-- текст экрана блокировки и живёт в другом жизненном цикле. Общая колонка развела бы
-- два смысла по одному имени — ровно то, что потом читают глазами в проде.
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS reboot_reason        TEXT    NOT NULL DEFAULT '';
-- 0 = «дефолт агента» (60 с), а НЕ «сейчас»: нулевое значение никогда не должно быть
-- самым деструктивным вариантом. API минимум — 10 с (меньше агент не примет), поэтому
-- явного «немедленно» в БД не существует, только очень короткая отсрочка.
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS reboot_delay_seconds INTEGER NOT NULL DEFAULT 0;

-- Частичный уникальный индекс: на устройство разом живёт не более ОДНОЙ недоставленной
-- заявки на перезагрузку. Повтор клика оператора обязан попадать в ТУ ЖЕ задачу —
-- новый task_id это вторая перезагрузка, и на нём машина уходит в цикл (агент
-- дедуплицирует durably по task_id, но чужой id для него — новая команда).
CREATE UNIQUE INDEX IF NOT EXISTS idx_tasks_one_pending_reboot
  ON tasks (device_id)
  WHERE task_type = 'reboot' AND status = 'pending';
