-- 042: tamper-evident аудит — хеш-цепочка над audit_log.
--
-- До этого журнал аудита был обычной таблицей: администратор БД (или тот, кто до
-- неё добрался) мог отредактировать строку или удалить её, не оставив следа.
-- Журнал, который нельзя проверить, в разборе инцидента не свидетельство, а мнение.
--
-- Каждая запись несёт номер в цепочке (seq), хеш предыдущей записи (prev_hash) и
-- собственный хеш (hash) от всех своих полей ВМЕСТЕ с prev_hash. Изменение любого
-- поля любой записи расходится с её hash; удаление записи из середины рвёт и
-- нумерацию, и связку prev_hash соседа.
--
-- 🔴 ЧЕСТНАЯ ГРАНИЦА: цепочка ловит правку и удаление, но НЕ останавливает того,
-- кто имеет право писать в БД и знает про неё — он пересчитает цепочку целиком.
-- Единственное, что делает её криптографически значимой, — вынос головы наружу,
-- туда, где противник её не перепишет (см. audit_anchors ниже и ежедневную
-- публикацию головы в лог сервера). Ровно поэтому цепочка стоит дёшево, но и
-- обещать по ней надо ровно то, что она даёт.
--
-- Идемпотентно (IF NOT EXISTS): schema_migrations в проекте нет, файлы
-- накатываются вручную через psql -f и могут быть применены повторно.

-- ---------------------------------------------------------------------------
-- 1. Колонки цепочки
-- ---------------------------------------------------------------------------

-- seq НЕ BIGSERIAL и не uuid: sequence оставляет дыры при откате транзакции, а
-- дыра в нумерации — ровно тот признак, по которому мы отличаем удаление записи от
-- легального усечения хвоста retention'ом. Номер выдаётся явно как «голова + 1»
-- под advisory-локом (storage.WriteAuditLog), поэтому откат не оставляет следа.
--
-- Все три колонки NULLABLE: записи, сделанные ДО наката этой миграции, в цепочку не
-- входят и никогда не войдут. Ретроспективно пересчитать их хеши технически можно,
-- но это была бы имитация: пересчёт по уже, возможно, подделанным данным даёт
-- валидную цепочку над подделкой. Проверка честно сообщает, сколько записей
-- предшествует началу цепочки и не покрыто ей.
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS seq       BIGINT;
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS prev_hash TEXT;
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS hash      TEXT;

-- Уникальность номера — вторая линия обороны к advisory-локу: если лок когда-нибудь
-- обойдут (другой путь записи, ручной INSERT), конфликт будет громким, а не тихой
-- вилкой в цепочке. Частичный индекс, потому что у до-цепочечных записей seq NULL.
CREATE UNIQUE INDEX IF NOT EXISTS idx_audit_log_seq
    ON audit_log (seq) WHERE seq IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 2. Канонизация и хеш — функцией в БД, а не в Go
-- ---------------------------------------------------------------------------

-- Хеш считается В POSTGRES, и это принципиально. details имеет тип JSONB, а JSONB
-- нормализуется при записи: порядок ключей меняется, дубликаты схлопываются,
-- пробелы уходят, числа переписываются. Хеш, посчитанный в Go от того, что мы
-- СОБИРАЛИСЬ записать, не совпал бы с хешем от того, что Postgres реально хранит, —
-- и вся цепочка разошлась бы на первой же записи с нетривиальным details.
-- Одна функция на оба пути (запись и проверка) исключает расхождение по построению.
--
-- Поля склеиваются с префиксом длины (`длина:значение`), а не через разделитель:
-- любой разделитель может встретиться внутри details или user_email, и тогда две
-- разные записи дали бы одну строку для хеширования. Префикс длины инъективен при
-- любом содержимом.
--
-- created_at имеет тип TIMESTAMPTZ (миграция 015 перевела в него все временные
-- колонки проекта), поэтому момент времени приводится к UTC ЯВНО: `AT TIME ZONE
-- 'UTC'` даёт timestamp без зоны детерминированно, не заглядывая в TimeZone сессии.
-- Без этого приведения to_char зависел бы от настройки соединения, функцию нельзя
-- было бы объявить IMMUTABLE, а проверка цепочки с другого клиента (psql оператора
-- с иной TimeZone) объявляла бы весь журнал подделанным.
CREATE OR REPLACE FUNCTION audit_chain_field(p TEXT) RETURNS TEXT
    LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT length(coalesce(p, ''))::text || ':' || coalesce(p, '')
$$;

CREATE OR REPLACE FUNCTION audit_row_hash(
    p_prev_hash   TEXT,
    p_seq         BIGINT,
    p_user_id     UUID,
    p_user_email  TEXT,
    p_action      TEXT,
    p_target_type TEXT,
    p_target_id   TEXT,
    p_details     JSONB,
    p_created_at  TIMESTAMPTZ
) RETURNS TEXT LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT encode(sha256(convert_to(
        audit_chain_field(p_prev_hash)   ||
        audit_chain_field(p_seq::text)   ||
        audit_chain_field(p_user_id::text) ||
        audit_chain_field(p_user_email)  ||
        audit_chain_field(p_action)      ||
        audit_chain_field(p_target_type) ||
        audit_chain_field(p_target_id)   ||
        audit_chain_field(coalesce(p_details::text, 'null')) ||
        audit_chain_field(to_char(p_created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'))
    , 'UTF8')), 'hex')
$$;

-- ---------------------------------------------------------------------------
-- 3. Якоря — то, что переживает retention
-- ---------------------------------------------------------------------------

-- CleanupOldData удаляет записи audit_log старше AUDIT_RETENTION_DAYS. Это законно,
-- но после усечения цепочку нельзя проследить до её начала: самая старая уцелевшая
-- запись ссылается на prev_hash, которого больше нет.
--
-- Якорь фиксирует «на момент T голова цепочки была seq=N с хешем H». Строки уходят,
-- якоря остаются. Благодаря им проверка отличает легальное усечение ПРЕФИКСА
-- (retention удаляет самое старое) от удаления из середины: во втором случае
-- ломается непрерывность seq, в первом — просто сдвигается начало.
--
-- Эту таблицу retention НЕ чистит. Она растёт на одну строку в сутки — 365 строк в
-- год, вечное хранение здесь не проблема.
CREATE TABLE IF NOT EXISTS audit_anchors (
    seq        BIGINT      PRIMARY KEY,
    hash       TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

