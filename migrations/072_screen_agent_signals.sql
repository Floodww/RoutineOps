-- 072: сервер начинает ЧИТАТЬ то, что агент присылает.
--
-- Три поля протокола агент заполнял с самого начала, а сервер не читал ни одного:
-- SessionHello.profile_fallback, SessionFrame.captured_at_ms и ScreenEvent.at_ms. Поле,
-- которое пишут и не читают, — это не «задел на будущее», а обещание, которого нет:
-- контракт объявляет его частью протокола, тесты его гоняют, а вопрос, ради которого оно
-- заведено, остаётся без ответа.
--
--   profile_fallback — агент НЕ ОПОЗНАЛ запрошенный профиль и взял low. Это расхождение
--   версий сервера и агента, и видно оно только здесь: картинка просто оказывается хуже
--   заказанной, а причина не называется нигде. Оператору при этом объяснять нечего.
--
--   telemetry_at — момент, на который агент снял счётчики сеанса. Телеметрия едет
--   durable-очередью и приходит С ЗАДЕРЖКОЙ, иногда через часы (агент был офлайн), а
--   доставка at-least-once: без метки времени поздний повтор старого замера затирал бы
--   свежие счётчики. Метка делает порядок применения независимым от порядка доставки.
--
-- Задержка ретрансляции (captured_at_ms) колонки не получает намеренно: это диагностика
-- канала, а не факт о сеансе. Её место — манифест записи (Manifest.max_lag_ms) и строка
-- лога при закрытии, рядом с остальными числами сеанса.

ALTER TABLE screen_sessions
  ADD COLUMN IF NOT EXISTS profile_fallback BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS telemetry_at TIMESTAMPTZ;

COMMENT ON COLUMN screen_sessions.profile_fallback IS
  'Агент не опознал запрошенный профиль и взял low — расхождение версий сервера и агента';
COMMENT ON COLUMN screen_sessions.telemetry_at IS
  'Момент, на который агент снял счётчики сеанса; защита от применения поздних повторов';

