-- 039: здоровье durable-очереди агента, приезжающее в heartbeat (proto
-- HeartbeatRequest.outbox_unavailable / degraded_detail).
--
-- Зачем колонки на devices, а не только строка в alerts: алерт — событие («в 14:02
-- очередь легла»), а оператору нужно СОСТОЯНИЕ («эта машина слепа прямо сейчас»).
-- Алерт можно принять, и он уедет из выдачи, пока причина жива; поле — нет.
--
-- Почему это вообще отдельный признак: outbox и есть канал доставки отчётов, статусов
-- лока и security-событий. Когда он мёртв, всё перечисленное умирает разом и молча —
-- устройство в панели выглядит здоровым, у него просто «ничего не происходит».
-- Полевой баг 2.5.1 на Windows (пустой DACL запирал каталог от самой службы) внешне
-- проявился ровно одним симптомом: залипшим статусом блокировки, замеченным глазами.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS outbox_unavailable BOOLEAN NOT NULL DEFAULT false;
-- Причина для оператора (текст ошибки ввода-вывода), уже обрезанная агентом до 200 Б.
-- Пусто при взведённом флаге допустимо: причину не всегда удаётся получить, и флаг без
-- причины лучше молчания.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS degraded_detail    TEXT    NOT NULL DEFAULT '';
-- Момент, с которого очередь лежит. NULL = не деградирует. Отдельно от alerts.created_at
-- потому, что алерт живёт своей жизнью (принят/вычищен retention), а «сколько уже
-- молчит» — первый вопрос оператора и он не должен зависеть от судьбы строки алерта.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS degraded_since     TIMESTAMPTZ;

