-- 054: резолв тенанта задачи для доставки (SECURITY DEFINER).
--
-- Зачем. Доставку задачи агенту исполняет фоновый asynq-обработчик: у него на входе
-- только task_id, тенанта в контексте нет и взяться ему неоткуда. Под app-ролью из 049
-- первый же запрос обработчика (GetTask) попадает под RLS и падает 22P02 — предикат 046
-- приводит пустой routineops.tenant_id к uuid. Полевой e2e 30.07 показал цену: командный
-- канал был мёртв ЦЕЛИКОМ (перезагрузка не доезжала, скриптовые политики не исполнялись),
-- при этом устройства исправно слали heartbeat и инвентарь, то есть в панели всё выглядело
-- живым.
--
-- Приём тот же, что у auth_device_tenant (047) и auth_oidc_provider (051): строка
-- находится DEFINER-функцией, а тенант берётся из неё и выставляется в GUC. Иначе
-- пришлось бы либо тащить tenant_id в payload всех одиннадцати точек постановки в
-- очередь, либо возвращать воркеру bypassrls — то есть отменять смысл 049.
--
-- Функция отдаёт ровно одну колонку одной строки по первичному ключу и никаких прав,
-- кроме чтения tenant_id, не даёт: знание «какому тенанту принадлежит задача» и так
-- есть у того, кто эту задачу создал.

CREATE OR REPLACE FUNCTION auth_task_tenant(p_task_id UUID)
RETURNS UUID
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT t.tenant_id FROM tasks t WHERE t.id = p_task_id;
$$;

