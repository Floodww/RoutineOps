#!/usr/bin/env bash
# check-installer-versions.sh — гейт свежести трекнутых установщиков.
#
# Сверяет версию ВНУТРИ build/msi/RoutineOps-agent.msi и build/pkg/RoutineOps-agent.pkg
# с AGENT_VERSION.
#
# 🔴 Зачем гейт на бинарь, лежащий в репозитории. Эти два файла — не артефакты сборки,
# а отдельная поверхность доставки, и она НЕ та же, что самообновление парка:
#   • install.sh и update.sh копируют их в releases/ БЕЗУСЛОВНО, оттуда их отдаёт
#     кнопка «Скачать MSI/PKG» в панели (по /downloads/);
#   • оба уезжают в публичный Free-срез байт-в-байт (export-free.sh их не трогает).
# Парк тем временем живёт самообновлением и про эти файлы ничего не знает. Поэтому их
# отставание никак себя не проявляет: парк здоров, релиз выпущен, а свежеподключаемая
# машина ставит прошлую версию — и ручная замена файла в releases/ отменяется следующим
# же `git pull && ./update.sh`.
#
# Ровно это и случилось: 05.08.2026 PKG был 2.6.0, а MSI — 2.5.9.0, отстав на релиз с
# 03.08. Проверялось до сих пор ничем: CI собирает боевой авторинг (build/msi/*.wxs) из
# свежесобранного exe, то есть проверяет РАЗМЕТКУ пакета, а не файл, который уезжает.
#
# Гейт fail-closed: нет инструмента — отказ, а не «пропускаем». Молчаливый пропуск здесь
# был бы хуже отсутствия гейта, потому что выглядел бы как проверка.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
MSI="$ROOT/build/msi/RoutineOps-agent.msi"
PKG="$ROOT/build/pkg/RoutineOps-agent.pkg"

fail=0
note() { printf '%s\n' "$1"; }
bad() { printf 'FAIL: %s\n' "$1" >&2; fail=1; }

# ── Чего ждём ────────────────────────────────────────────────────────────────────
if [ ! -f "$ROOT/AGENT_VERSION" ]; then
  echo "ОШИБКА: нет $ROOT/AGENT_VERSION — сверять не с чем" >&2
  exit 2
fi
WANT=$(tr -d ' \t\r\n' < "$ROOT/AGENT_VERSION")
case "$WANT" in
  [0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "ОШИБКА: AGENT_VERSION=$WANT не похож на x.y.z" >&2; exit 2 ;;
esac
note "== версии установщиков: ждём $WANT (AGENT_VERSION) =="

# ── MSI ──────────────────────────────────────────────────────────────────────────
#
# Сравниваем ПЕРВЫЕ ТРИ поля ProductVersion. Четвёртое — счётчик перезаливок одной и
# той же версии агента, и Windows Installer его игнорирует: MajorUpgrade сравнивает
# ровно три первых. Требовать совпадения четвёртого значило бы запретить пересборку
# пакета без бампа агента.
if [ ! -f "$MSI" ]; then
  bad "нет $MSI — кнопке «Скачать MSI» нечего отдавать"
elif ! command -v msiinfo >/dev/null 2>&1; then
  echo "ОШИБКА: нет msiinfo (пакет msitools) — версию MSI прочитать нечем" >&2
  exit 2
else
  # `|| true` обязателен: под `set -e` + pipefail упавший msiinfo (битый файл, не MSI)
  # убивал бы скрипт прямо на подстановке — гейт падал бы БЕЗ диагноза, с голым кодом 1.
  got=$(msiinfo export "$MSI" Property 2>/dev/null | awk '$1=="ProductVersion"{print $2; exit}' || true)
  if [ -z "$got" ]; then
    bad "в $MSI не читается ProductVersion — пакет битый либо не MSI"
  else
    short=$(printf '%s' "$got" | cut -d. -f1-3)
    if [ "$short" = "$WANT" ]; then
      note "  MSI  $got — ок"
    else
      bad "MSI внутри $got (первые три поля $short), а AGENT_VERSION=$WANT.
      Пересобрать: make msi-exe → build/msi/build-msi.ps1 -Version $WANT.0 на Windows,
      затем закоммитить build/msi/RoutineOps-agent.msi."
    fi
  fi
fi

# ── PKG ──────────────────────────────────────────────────────────────────────────
#
# .pkg — архив xar; версия лежит атрибутом version у элемента <pkg-info>. Читаем именно
# его: в PackageInfo есть ещё version="1.0" от XML-декларации и format-version, и
# наивный grep по version= хватает не то.
if [ ! -f "$PKG" ]; then
  bad "нет $PKG — кнопке «Скачать PKG» нечего отдавать"
else
  pkginfo=""
  if command -v bsdtar >/dev/null 2>&1; then
    pkginfo=$(bsdtar -xOf "$PKG" PackageInfo 2>/dev/null || true)
  elif tar --version 2>/dev/null | grep -qi bsdtar; then
    pkginfo=$(tar -xOf "$PKG" PackageInfo 2>/dev/null || true)
  elif command -v xar >/dev/null 2>&1; then
    tmp=$(mktemp -d)
    ( cd "$tmp" && xar -xf "$PKG" PackageInfo >/dev/null 2>&1 ) || true
    [ -f "$tmp/PackageInfo" ] && pkginfo=$(cat "$tmp/PackageInfo")
    rm -rf "$tmp"
  else
    echo "ОШИБКА: нечем распаковать xar (нужен bsdtar/libarchive-tools либо xar)" >&2
    exit 2
  fi
  if [ -z "$pkginfo" ]; then
    bad "в $PKG не читается PackageInfo — пакет битый либо не xar"
  else
    got=$(printf '%s' "$pkginfo" | tr '>' '\n' | grep '<pkg-info' \
      | grep -oE '[[:space:]]version="[0-9][0-9.]*"' | head -1 | cut -d'"' -f2)
    if [ -z "$got" ]; then
      bad "в PackageInfo нет атрибута version у <pkg-info>"
    elif [ "$got" = "$WANT" ]; then
      note "  PKG  $got — ок"
    else
      bad "PKG внутри $got, а AGENT_VERSION=$WANT.
      Пересобрать: make pkg-mac на macOS, затем закоммитить build/pkg/RoutineOps-agent.pkg."
    fi
  fi
fi

# ---------------------------------------------------------------------------
# Переносы строк в батниках доставки.
#
# 🔴 Поймано в поле: пользователь скачал uninstall.bat с GitHub, запустил от админа и
# получил град «'TamperProtection' is not recognized», «'загрузитесь' is not recognized».
# cmd.exe читает батник ПОСТРОЧНО и на одиночном LF разбирает его со сдвигом: строка REM
# перестаёт быть комментарием, а кириллица внутри неё исполняется как команда. Скрипт не
# отрабатывает, а выглядит это как «батник сломан».
#
# Файл лежит в git с `-text` (см. .gitattributes), то есть байты в объекте = байты в
# raw-выдаче GitHub. Раз git больше ничего не нормализует — за форматом следит этот гейт.
# ---------------------------------------------------------------------------
#
# Проверяем КАЖДУЮ строку, а не «есть ли хоть один CRLF».
#
# Прежняя проверка спрашивала «встречается ли \r в файле» и на этом успокаивалась. Файл
# со СМЕШАННЫМИ переносами её проходил — а cmd.exe разбирает со сдвигом ровно те строки,
# что остались с одиночным LF, и хватает одной. Сценарий не гипотетический: батник правят
# с macOS/Linux, где редактор дописывает LF в CRLF-файл, и гейт молча говорил «ок».
# ---------------------------------------------------------------------------
echo "== переносы строк в батниках =="
for bat in $(find "$ROOT" -name '*.bat' -not -path '*/.git/*' | sort); do
  rel=${bat#"$ROOT"/}
  # Проверяем ФОРМУ ВСЕГО ФАЙЛА, а не «есть ли строки без CR».
  #
  # Построчные проверки (и старая «есть хоть один CRLF», и её ужесточение через awk)
  # разбивают файл по \n и смотрят последний байт записи. Мимо них проезжают ровно те
  # виды порчи, которые в поле и встречаются:
  #   • CR-only (старый Mac / некоторые редакторы) — \n нет вовсе, cmd.exe видит ОДНУ
  #     строку и выполняет только первую команду;
  #   • CR в СЕРЕДИНЕ строки — «a\r\nb\rc\r\n»: b и c склеиваются в одну логическую строку;
  #   • нет завершающего перевода строки у последней команды.
  # Ни один из трёх не даёт «строки без CR», поэтому построчная проверка их не видит.
  #
  # Регулярка требует буквально: файл = последовательность строк без CR и LF внутри,
  # каждая закрыта \r\n, и на этом файл кончается. Пустой файл не проходит: пустой .bat —
  # это сломанная доставка, а не «нечего проверять».
  if perl -0777 -ne 'exit(!(length($_) && /\A(?:[^\r\n]*\r\n)+\z/))' "$bat"; then
    note "  $rel — CRLF во всех строках, ок"
  else
    bad "$rel: переносы строк не CRLF, либо в файле есть одиночный CR, либо последняя
      строка не закрыта переводом — cmd.exe разберёт файл со сдвигом.
      Починить: perl -0777 -pi -e 's/\r\n|\r|\n/\r\n/g; \$_ .= \"\r\n\" unless /\r\n\z/' $rel"
  fi
done

# ---------------------------------------------------------------------------
# Скрипт снятия ВНУТРИ трекнутого MSI.
#
# 🔴 Тот же класс, что и версии выше: проверялся АВТОРИНГ, а не то, что едет. `.wxs`
# кладёт uninstall.bat в каталог установки, контрактный тест это подтверждает, CI собирает
# пакет из авторинга — и все трое зелёные, пока трекнутый build/msi/RoutineOps-agent.msi
# собран из ПРЕЖНЕГО авторинга и батника внутри не содержит. Администратор, скачавший MSI
# кнопкой «Скачать», получает пакет без скрипта снятия и идёт искать его в браузере — то
# есть ровно та проблема, которую правка авторинга якобы закрыла.
#
# Сверяем побайтово: батник — исполняемый контракт с агентом (он зовёт подкоманды
# tamper-cleanup и msi-unregister), и «похожая» версия внутри пакета здесь не годится.
# ---------------------------------------------------------------------------
echo "== скрипт снятия внутри MSI =="
BAT="$ROOT/build/msi/uninstall.bat"
if [ ! -f "$MSI" ]; then
  : # уже отрапортовано выше
elif [ ! -f "$BAT" ]; then
  bad "нет $BAT — сверять нечего"
elif ! command -v msiextract >/dev/null 2>&1; then
  echo "ОШИБКА: нет msiextract (пакет msitools) — содержимое MSI прочитать нечем" >&2
  exit 2
else
  tmpd=$(mktemp -d)
  # Код возврата msiextract СОХРАНЯЕМ. Без этого «пакет не распаковался» (битый файл,
  # внешний .cab, burn-бандл вместо MSI) выглядело бы как «в пакете нет батника», и
  # человек шёл бы пересобирать исправный, но повреждённый при передаче файл. Соседняя
  # проверка версии выше эту дисциплину уже соблюдает — «не читается» ≠ «не совпало».
  xrc=0
  ( cd "$tmpd" && msiextract "$MSI" >/dev/null 2>&1 ) || xrc=$?
  # Никакого `| head -1`: под `set -o pipefail` закрытый пайп даёт SIGPIPE у find, и
  # скрипт умирает с голым кодом 141 — без диагноза и без уборки временного каталога.
  # Заодно требуем РОВНО ОДНО совпадение: при двух копиях батника в пакете `head -1`
  # брал бы произвольную (порядок обхода ФС), и гейт зеленел бы через раз на устаревшей.
  inner=$(find "$tmpd" -name 'uninstall.bat' -type f | sort)
  n=$(printf '%s' "$inner" | grep -c . || true)
  if [ "$xrc" -ne 0 ] && [ "$n" -eq 0 ]; then
    bad "msiextract не смог распаковать $MSI (код $xrc) — файл повреждён либо это не MSI.
      Сверить содержимое нечем. Пересборка тут НЕ поможет: сначала проверьте сам файл."
  elif [ "$n" -eq 0 ]; then
    bad "в $MSI НЕТ uninstall.bat — пакет собран из прежнего авторинга.
      Кнопка «Скачать MSI» отдаёт установщик без скрипта снятия, и администратору снова
      придётся искать его в исходниках. Пересобрать MSI на Windows-боксе."
  elif [ "$n" -ne 1 ]; then
    bad "в $MSI несколько uninstall.bat ($n шт.) — какой из них уедет на диск, зависит от
      авторинга, а не от этой проверки. Разберитесь с пакетом:
$inner"
  elif ! cmp -s "$inner" "$BAT"; then
    bad "uninstall.bat внутри $MSI отличается от build/msi/uninstall.bat — пакет отстал
      от репозитория. Скрипт снятия зовёт подкоманды агента, и старая копия внутри
      пакета молча пропустит новые шаги. Пересобрать MSI."
  else
    note "  uninstall.bat внутри MSI совпадает с репозиторием, ок"
  fi
  rm -rf "$tmpd"
fi

# ---------------------------------------------------------------------------
# Редакция трекнутых артефактов.
#
# 🔴 Тот же класс, что и две проверки выше — «проверяем то, что едет», — но в другую
# сторону. Эти три файла уезжают в публичный Free-срез БАЙТ-В-БАЙТ и раздаются кнопкой
# «Скачать», поэтому обязаны быть open-core ВСЕГДА. Enterprise-сборку сюда класть нельзя:
# это раздача закрытого кода. Обратный случай (артефакт собрали с тегом и закоммитили)
# ловил только полный прогон scripts/export-free.sh — он требует bash 4+ и docker и живёт
# в конце цепочки, перед публикацией среза, то есть после пуша.
#
# Проверяется СИМВОЛ в бинаре, а не переменная окружения сборки: переменную можно забыть,
# символ забыть нельзя. Гейт fail-closed: нет чем распаковать — отказ, а не пропуск.
#
# Чего этот гейт НЕ говорит: что парк получает ту же редакцию. Парк живёт самообновлением,
# его агента собирает install.sh/update.sh по BUILD_TAGS — там стоит тот же гейт на
# СОБРАННЫЙ бинарь (scripts/agent-edition-guard.sh), и на enterprise-инсталляции ждётся
# ровно обратное. Один скрипт, два ожидания.
# ---------------------------------------------------------------------------
echo "== редакция трекнутых артефактов (обязаны быть open-core) =="
GUARD="$ROOT/scripts/agent-edition-guard.sh"
[ -x "$GUARD" ] || { echo "ОШИБКА: нет $GUARD — редакцию проверить нечем" >&2; exit 2; }

# Пустой первый аргумент = ждём open-core. Диагностику гейт печатает сам.
edition_open_core() { # <файл> <метка>
  local rc=0
  sh "$GUARD" "" "$1" "$2" || rc=$?
  case "$rc" in
    0) ;;
    1) bad "$2: редакция не open-core (диагностика гейта выше)" ;;
    *) echo "ОШИБКА: редакция $2 не проверена — гейт вернул $rc" >&2; exit 2 ;;
  esac
}

DARWIN="$ROOT/build/darwin/agent_darwin_arm64"
if [ ! -f "$DARWIN" ]; then
  bad "нет $DARWIN — macOS-парку публиковать нечего"
else
  edition_open_core "$DARWIN" "build/darwin/agent_darwin_arm64"
fi

# exe ВНУТРИ MSI: сам .msi сжат, и grep по контейнеру не видит строк бинаря — он ответил бы
# «токена нет» на любом пакете, включая enterprise. Поэтому распаковываем.
if [ -f "$MSI" ] && command -v msiextract >/dev/null 2>&1; then
  tmpd=$(mktemp -d)
  xrc=0
  ( cd "$tmpd" && msiextract "$MSI" >/dev/null 2>&1 ) || xrc=$?
  inner_exe=$(find "$tmpd" -name '*.exe' -type f | sort)
  n=$(printf '%s' "$inner_exe" | grep -c . || true)
  if [ "$n" -eq 0 ]; then
    bad "в $MSI нет ни одного .exe (msiextract код $xrc) — редакцию проверить нечем"
  elif [ "$n" -ne 1 ]; then
    bad "в $MSI несколько .exe ($n шт.) — непонятно, какой едет:
$inner_exe"
  else
    edition_open_core "$inner_exe" "exe внутри MSI"
  fi
  rm -rf "$tmpd"
fi

# Payload у .pkg — gzip'нутый cpio; токен ищем в распакованном потоке.
if [ -f "$PKG" ]; then
  tmpd=$(mktemp -d)
  if command -v bsdtar >/dev/null 2>&1; then
    bsdtar -xOf "$PKG" '*Payload' 2>/dev/null | gunzip -c > "$tmpd/payload" 2>/dev/null || true
  elif command -v xar >/dev/null 2>&1; then
    ( cd "$tmpd" && xar -xf "$PKG" Payload >/dev/null 2>&1 ) || true
    [ -f "$tmpd/Payload" ] && { gunzip -c "$tmpd/Payload" > "$tmpd/payload" 2>/dev/null || true; }
  else
    echo "ОШИБКА: нечем распаковать Payload из $PKG (нужен bsdtar/libarchive-tools либо xar)" >&2
    exit 2
  fi
  if [ ! -s "$tmpd/payload" ]; then
    rm -rf "$tmpd"
    echo "ОШИБКА: Payload из $PKG не распаковался — редакцию проверить нечем" >&2
    exit 2
  fi
  edition_open_core "$tmpd/payload" "payload внутри PKG"
  rm -rf "$tmpd"
fi

if [ "$fail" -ne 0 ]; then
  echo "" >&2
  echo "С установщиком в репозитории что-то не так (см. выше). Это НЕ про парк — он живёт" >&2
  echo "самообновлением и этих файлов не видит. Это про кнопку «Скачать» в панели, куда" >&2
  echo "их безусловно копирует update.sh, и про публичный Free-срез." >&2
  exit 1
fi
echo "OK: установщики в репозитории соответствуют AGENT_VERSION"
