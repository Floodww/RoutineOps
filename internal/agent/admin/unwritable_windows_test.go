//go:build windows

package admin

import (
	"os/exec"
	"os/user"
	"testing"
)

// makeUnwritable запирает каталог состояния так, как он запирается В ПОЛЕ: явным
// запрещающим ACE.
//
// os.Chmod на Windows переключает только атрибут «только чтение» самого каталога
// и созданию файлов ВНУТРИ него не мешает вовсе. Тест на chmod здесь проходил бы
// по недоразумению — точнее, не проходил: условие не воспроизводилось, Save
// срабатывал, права выдавались, и падало утверждение. Проверять надо ту же
// границу, на которой баг живёт: полевой отказ 2.5.1 на Windows — это именно
// испорченный DACL на каталоге состояния, а не права POSIX.
func makeUnwritable(t *testing.T, dir string) {
	t.Helper()
	u, err := user.Current()
	if err != nil {
		t.Skipf("не определить текущего пользователя: %v", err)
	}
	// (OI)(CI) — наследование на файлы и подкаталоги, чтобы запрет накрыл и
	// временный файл, который создаёт атомарная запись состояния.
	if out, err := exec.Command("icacls", dir, "/deny", u.Username+":(OI)(CI)(W)").CombinedOutput(); err != nil {
		t.Skipf("icacls /deny не отработал: %v: %s", err, out)
	}
	// Снятие запрета регистрируется ПОСЛЕ создания каталога тестом, поэтому в
	// LIFO-порядке выполнится раньше уборки TempDir — иначе уборка не смогла бы
	// удалить запертый каталог.
	t.Cleanup(func() {
		_ = exec.Command("icacls", dir, "/remove:d", u.Username).Run()
	})
}
