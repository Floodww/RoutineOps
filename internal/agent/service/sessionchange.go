package service

// События смены состояния сессии пользователя (docs/remote-desktop-contract.md §9.11).
//
// Почему это отдельный механизм, а не «посмотрим статус сессии по опросу»: при Win+L
// сессия остаётся WTSActive, WTSQueryUserToken по-прежнему выдаёт токен, захватчик жив и
// здоров — и продолжает снимать экран, на котором ОС рисует чёрное. Снаружи это выглядит
// как «сотрудник заблокировал компьютер, а его всё равно смотрят». Отличить это состояние
// опросом нечем; единственный источник правды — уведомление SCM.
//
// Служба обязана явно запросить SERVICE_ACCEPT_SESSIONCHANGE: без него WTS_SESSION_LOCK,
// UNLOCK, LOGOFF и DISCONNECT не приходят вовсе.

// SessionEvent — уведомление SCM о смене состояния сессии.
//
// Event — сырой код WTS_* от Windows, без интерпретации: разбирать его — дело того, кто
// подписался (см. screen.ReasonForWTS). Пакет службы не должен знать про сеансы удалённого
// стола, иначе следующая фича с таким же требованием потянет сюда и свои коды.
type SessionEvent struct {
	Event     uint32
	SessionID uint32
}
