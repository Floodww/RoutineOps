// Package reboot планирует перезагрузку устройства по команде оператора.
//
// Отсрочку исполняет ПЛАНИРОВЩИК ОС (shutdown), а не таймер внутри агента:
// таймер умер бы вместе с процессом при самообновлении, рестарте службы или
// падении — перезагрузка тихо не произошла бы, а оператор видел бы задачу
// выполненной. Отдав отсрочку ОС, мы получаем ровно одну точку отказа, и она
// проверяема сразу: команда либо принята планировщиком, либо вернула ошибку,
// которую агент отчитывает как провал задачи.
package reboot

import (
	"context"
	"strings"
	"time"
	"unicode"
)

const (
	// DefaultDelay — отсрочка, если сервер её не задал (delay_seconds = 0).
	// По её истечении перезагрузка ПРИНУДИТЕЛЬНАЯ: без этого одно окно с
	// несохранённым файлом молча отменяет команду оператора, и машина остаётся в
	// прежнем состоянии без единого следа — худший исход, чем закрытое приложение.
	// Сама отсрочка и есть защита несохранённой работы, поэтому она не нулевая.
	DefaultDelay = 60 * time.Second

	// MinDelay — минимальная отсрочка даже по явному запросу сервера. Ноль
	// секунд не даём: сотрудник должен увидеть предупреждение раньше, чем
	// погаснет экран, иначе перезагрузка выглядит как сбой устройства и создаёт
	// заявку в поддержку вместо ожидаемого эффекта.
	MinDelay = 10 * time.Second

	// MaxDelay — потолок отсрочки. Больше суток — это уже не «перезагрузить
	// устройство», а забытая задача, которая сработает в непредсказуемый момент;
	// такие сценарии решаются расписанием на сервере, а не отложенной командой.
	MaxDelay = 24 * time.Hour

	// maxMessageRunes — предел длины текста для сотрудника. У Windows
	// `shutdown /c` жёсткий лимит (512 символов), с запасом обрезаем короче;
	// длинная простыня всё равно не читается в системном предупреждении.
	maxMessageRunes = 400
)

// Scheduler — планировщик перезагрузки через средства ОС. Пустая структура:
// состояния нет, вынесен типом только чтобы подключаться интерфейсом в executor
// (тот не должен зависеть от этого пакета и должен тестироваться с фейком).
type Scheduler struct{}

// Schedule планирует перезагрузку через delay с текстом reason для сотрудника.
// Возвращает ФАКТИЧЕСКУЮ отсрочку — она может отличаться от запрошенной
// (границы clampDelay, округление до минут на macOS/Linux), и вызывающий обязан
// отчитаться серверу именно ей, иначе в аудите останется время, которого не было.
//
// Возврат без ошибки означает, что команду принял планировщик ОС, а не что
// перезагрузка уже случилась.
func (Scheduler) Schedule(ctx context.Context, delay time.Duration, reason string) (time.Duration, error) {
	d := clampDelay(delay)
	return schedule(ctx, d, sanitizeMessage(reason))
}

// clampDelay приводит запрошенную отсрочку к рабочим границам. d <= 0 трактуется
// как «поле не задано» → дефолт: отсутствие значения не должно означать самый
// деструктивный вариант (мгновенная перезагрузка без предупреждения).
func clampDelay(d time.Duration) time.Duration {
	switch {
	case d <= 0:
		return DefaultDelay
	case d < MinDelay:
		return MinDelay
	case d > MaxDelay:
		return MaxDelay
	default:
		return d
	}
}

// sanitizeMessage готовит текст для системного предупреждения: переводы строк и
// табы сворачиваются в пробелы (многострочный текст ломает вывод `shutdown /c` и
// wall-сообщение), лишние пробелы сжимаются, длина режется по границе рун — на
// байтах обрезка порвала бы кириллицу пополам и предупреждение стало бы
// нечитаемым ровно там, где важна причина.
func sanitizeMessage(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	space := true // ведущие пробелы не пишем
	for _, r := range s {
		switch {
		case unicode.IsSpace(r):
			if !space {
				b.WriteRune(' ')
				space = true
			}
		case unicode.IsControl(r):
			// Управляющие символы выкидываем целиком: в аргументе командной
			// строки они бесполезны, а в логах и аудите — мусор.
		default:
			b.WriteRune(r)
			space = false
		}
	}
	out := strings.TrimSpace(b.String())
	runes := []rune(out)
	if len(runes) > maxMessageRunes {
		out = strings.TrimSpace(string(runes[:maxMessageRunes]))
	}
	return out
}
