import { describe, expect, it } from "vitest"

import { inputOutcome } from "./screeninput"

// 🔴 Полевой баг, ради которого развилка вообще вынесена из компонента.
//
// Первая пачка ввода уходит в первые секунды сеанса — пока приглашение едет на устройство,
// а захватчик поднимается. Стрима в этот момент ещё нет, и сервер отвечал 409: тем же
// кодом, что «управление возвращено» и «сеанс кончился». Панель схлопывала все три в
// терминальный исход и гасила управление ДО КОНЦА СЕАНСА — при том что сервер его не
// отзывал (в БД control=t, control_returned_at=NULL). Лечилось только новым сеансом.
//
// Серверная половина контракта проверяется в
// internal/server/api/screen_input_early_ent_test.go: там «ещё не открыт» стал 503.
// Здесь — что панель на 503 управление НЕ хоронит.
describe("inputOutcome", () => {
  it("503 — временный отказ, управление остаётся", () => {
    // Два источника, ответ один: затор outbox у агента и «стрим ещё не открыт».
    // Панели различать их незачем — обе ситуации значат «повтори позже».
    expect(inputOutcome(503)).toBe("retry")
  })

  it("409 и 410 — окончательные, слать больше нечего", () => {
    expect(inputOutcome(409)).toBe("dead")
    expect(inputOutcome(410)).toBe("dead")
  })

  it("остальное не трогает управление", () => {
    // 500 в журнале ввода, 413 на длинной пачке, сеть — это ошибки ОТПРАВКИ, а не
    // приговор сеансу. Похоронить управление здесь значило бы потерять его из-за
    // одной моргнувшей сети.
    for (const status of [400, 413, 500, 502, 504, undefined]) {
      expect(inputOutcome(status)).toBe("unknown")
    }
  })
})
